import androidx.compose.runtime.Composable

/**
 * The Home Finance design system.
 *
 * Two schemes, one brand: a clean white background with an emerald-green primary colour is the
 * shipped light theme, and the dark theme is the same emerald lifted for dark surfaces rather than
 * a separate design. Which one is drawn is the household's choice ([ThemeMode]), defaulting to the
 * light one so an existing installation looks unchanged after an upgrade.
 *
 * Dynamic colour is deliberately not used, so the brand green is identical on every device instead
 * of being replaced by the wallpaper-derived palette.
 *
 * The light scheme is listed first and keeps the exact token names the app shipped with; anything
 * that reaches for a colour directly rather than through [MaterialTheme] still finds it.
 */
val HomeFinanceLightColorScheme = lightColorScheme(
    primary = EmeraldPrimary,
    onPrimary = EmeraldOnPrimary,
    primaryContainer = EmeraldPrimaryContainer,
    onPrimaryContainer = EmeraldOnPrimaryContainer,
    secondary = Secondary,
    onSecondary = OnSecondary,
    secondaryContainer = SecondaryContainer,
    onSecondaryContainer = OnSecondaryContainer,
    tertiary = Tertiary,
    onTertiary = OnTertiary,
    tertiaryContainer = TertiaryContainer,
    onTertiaryContainer = OnTertiaryContainer,
    error = ErrorRed,
    onError = OnErrorRed,
    errorContainer = ErrorRedContainer,
    onErrorContainer = OnErrorRedContainer,
    background = BackgroundLight,
    onBackground = OnBackgroundLight,
    surface = SurfaceLight,
    onSurface = OnSurfaceLight,
    surfaceVariant = SurfaceVariantLight,
    onSurfaceVariant = OnSurfaceVariantLight,
    outline = OutlineLight,
    outlineVariant = OutlineVariantLight,
    scrim = ScrimLight,
    inverseSurface = InverseSurfaceLight,
    inverseOnSurface = InverseOnSurfaceLight,
    inversePrimary = InversePrimaryLight,
    surfaceDim = SurfaceDimLight,
